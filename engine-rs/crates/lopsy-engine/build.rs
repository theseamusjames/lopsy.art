use std::fs;
use std::path::Path;

/// Write each shader as the backend compiles it into `$OUT_DIR/shaders/`,
/// under the same relative paths: the GLSL ES 3.00 translation for WebGL,
/// or the preprocessed WGSL for wgpu. `gpu::shader` embeds them from there.
fn translate_shaders(out_dir: &Path) {
    let root = Path::new("src/gpu/shaders");
    println!("cargo:rerun-if-changed={}", root.display());
    let is_wgpu = std::env::var_os("CARGO_FEATURE_WGPU").is_some();
    let extension = if is_wgpu { "wgsl" } else { "glsl" };
    // wgpu binds by layout, so its text opens with the shader's reflection.
    let source = |translated: &'_ lopsy_shaderc::Translated| -> String {
        if is_wgpu { translated.reflection.header() + &translated.wgsl } else { translated.glsl.clone() }
    };
    let outputs = lopsy_shaderc::translate_all(root).unwrap_or_else(|e| panic!("{e}"));
    for output in &outputs {
        let dest = out_dir.join("shaders").join(&output.path).with_extension(extension);
        fs::create_dir_all(dest.parent().unwrap()).unwrap();
        fs::write(&dest, source(&output.translated)).unwrap();
    }
    for set in lopsy_shaderc::VARIANT_SETS {
        let variants: Vec<String> = (0..set.count)
            .map(|value| {
                let path = Path::new(set.path).with_extension(format!("{value}.wgsl"));
                let output = outputs.iter().find(|o| o.path == path).expect("a variant was not translated");
                source(&output.translated)
            })
            .collect();
        let variants: Vec<&str> = variants.iter().map(String::as_str).collect();
        let dest = out_dir.join("shaders").join(set.path).with_extension("variants.rs");
        fs::write(&dest, variant_sources(&variants)).unwrap();
    }
}

/// A `VariantSources` literal for `gpu::shader`. Variant 0 is written whole;
/// the rest share most of their text, so the lines they all start with and
/// all end with are written once and each keeps only its middle.
fn variant_sources(variants: &[&str]) -> String {
    let rest: Vec<Vec<&str>> = variants[1..].iter().map(|v| v.split_inclusive('\n').collect()).collect();
    let shortest = rest.iter().map(Vec::len).min().unwrap_or(0);
    let prefix = (0..shortest).take_while(|&i| rest.iter().all(|v| v[i] == rest[0][i])).count();
    let suffix = (0..shortest - prefix)
        .take_while(|&i| rest.iter().all(|v| v[v.len() - 1 - i] == rest[0][rest[0].len() - 1 - i]))
        .count();
    let middles: Vec<String> = rest.iter().map(|v| format!("{:?}", v[prefix..v.len() - suffix].concat())).collect();
    let first = rest.first().map(Vec::as_slice).unwrap_or(&[]);
    format!(
        "VariantSources {{\n    first: {:?},\n    prefix: {:?},\n    middles: &[\n        {},\n    ],\n    suffix: {:?},\n}}\n",
        variants[0],
        first[..prefix].concat(),
        middles.join(",\n        "),
        first[first.len() - suffix..].concat(),
    )
}

fn main() {
    translate_shaders(Path::new(&std::env::var("OUT_DIR").unwrap()));

    let brushes_dir = Path::new("../../brushes");
    println!("cargo:rerun-if-changed={}", brushes_dir.display());

    let out_dir = std::env::var("OUT_DIR").unwrap();
    let dest = Path::new(&out_dir).join("builtin_brushes.rs");

    let mut includes = String::new();
    let mut match_arms = String::new();
    let mut list_entries = String::new();

    let abs_brushes = fs::canonicalize(brushes_dir).unwrap_or_else(|_| brushes_dir.to_path_buf());
    if let Ok(entries) = fs::read_dir(&abs_brushes) {
        let mut names: Vec<(String, String)> = Vec::new();
        for entry in entries.flatten() {
            let path = entry.path();
            if path.extension().map_or(false, |e| e == "png") {
                let stem = path.file_stem().unwrap().to_string_lossy().to_string();
                let const_name = format!(
                    "BRUSH_{}",
                    stem.to_uppercase().replace('-', "_").replace(' ', "_")
                );
                let abs_path = fs::canonicalize(&path).unwrap();
                let abs_str = abs_path.display().to_string().replace('\\', "/");
                names.push((stem, const_name.clone()));
                includes.push_str(&format!(
                    "const {const_name}: &[u8] = include_bytes!(\"{abs_str}\");\n"
                ));
                println!("cargo:rerun-if-changed={}", abs_path.display());
            }
        }
        names.sort_by(|a, b| a.0.cmp(&b.0));
        for (stem, const_name) in &names {
            match_arms.push_str(&format!(
                "        \"{stem}\" => Some({const_name}.to_vec()),\n"
            ));
            list_entries.push_str(&format!("    names.push_str(\"{stem},\");\n"));
        }
    }

    let code = format!(
        r##"// Auto-generated by build.rs — do not edit
{includes}
pub fn get_builtin_brush_tip_generated(name: &str) -> Option<Vec<u8>> {{
    match name {{
{match_arms}        _ => None,
    }}
}}

pub fn list_builtin_brush_tips() -> String {{
    let mut names = String::new();
{list_entries}    names
}}
"##
    );

    fs::write(dest, code).unwrap();
}
